func TestRunDisabledEcosystemIsPartial(t *testing.T) {
	e := newEnv(t, "project-a")
	e.run(t)
	// Only npm is enabled now, and only its database is present: composer.lock
	// is left out of the scan and its findings are kept.
	npmOnly := t.TempDir()
	zp := osvdb.ZipPath(npmOnly, "npm")
	if err := os.MkdirAll(filepath.Dir(zp), 0o755); err != nil {
		t.Fatal(err)
	}
	b, err := os.ReadFile(osvdb.ZipPath(osvRoot, "npm"))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(zp, b, 0o644); err != nil {
		t.Fatal(err)
	}
	r, err := Run(context.Background(), e.deps, e.proj, Options{OSVRoot: npmOnly, Ecosystems: []string{"npm"}})
	if err != nil {
		t.Fatalf("Run: %v (the Packagist database is not needed)", err)
	}
	if r.Status != ScanPartial || r.Gone != 0 || r.Still != 1 {
		t.Fatalf("status %s gone %d still %d errors %v", r.Status, r.Gone, r.Still, r.Errors)
	}
	disabled := false
	for _, m := range r.Manifests {
		if m.RelPath == "composer.lock" {
			disabled = errors.Is(m.Err, ErrEcosystemDisabled) && strings.Contains(m.Error, "osv.packagist")
		}
	}
	if !disabled {
		t.Errorf("composer.lock not reported as disabled: %+v", r.Manifests)
	}
	st := e.statuses(t)
	if st["ACME-2026-0001"] != StatusNew || st["ACME-2026-0002"] != StatusNew || st["ACME-2026-0101"] != StatusPending {
		t.Errorf("statuses %v", st)
	}
}
