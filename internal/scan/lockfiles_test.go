func TestFindLockfilesSeesYarnAndPnpm(t *testing.T) {
	root := t.TempDir()
	for _, f := range []string{"yarn.lock", "app/pnpm-lock.yaml", "web/package-lock.json", "composer.lock"} {
		p := filepath.Join(root, filepath.FromSlash(f))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	found, _, err := findLockfiles(root, DefaultExclude)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, lf := range found {
		got[lf.rel] = lf.ecosystem
	}
	want := map[string]string{"yarn.lock": "npm", "app/pnpm-lock.yaml": "npm", "web/package-lock.json": "npm", "composer.lock": "Packagist"}
	if fmt.Sprint(got) != fmt.Sprint(want) {
		t.Errorf("found %v, want %v", got, want)
	}
}

const yarnV1Header = "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"

func TestCheckContentYarnV1EmptyAndUnreadable(t *testing.T) {
	if err := checkContent("yarn.lock", []byte(yarnV1Header)); err != nil {
		t.Errorf("empty v1 lockfile: %v", err)
	}
	full := yarnV1Header + "vuln-pkg@^1.0.0:\n  version \"1.0.0\"\n"
	if err := checkContent("yarn.lock", []byte(full)); err == nil {
		t.Error("a v1 lockfile with a package the scanner skipped must be unreadable")
	}
	if err := checkContent("yarn.lock", []byte("{{ not a lockfile")); err == nil {
		t.Error("garbage accepted")
	}
}

func TestCheckContentPnpmAndBerry(t *testing.T) {
	for _, c := range []struct {
		name, body string
		empty      bool
	}{
		{"yarn.lock", "__metadata:\n  version: 6\n  cacheKey: 8\n", true},
		{"yarn.lock", "__metadata:\n  version: 6\n\n\"vuln-pkg@npm:^1.0.0\":\n  version: 1.0.0\n", false},
		{"pnpm-lock.yaml", "lockfileVersion: '9.0'\n", true},
		{"pnpm-lock.yaml", "lockfileVersion: '9.0'\nimporters:\n  .: {}\n", true},
		{"pnpm-lock.yaml", "lockfileVersion: '9.0'\npackages:\n  vuln-pkg@1.0.0:\n    resolution: {integrity: x}\n", false},
		{"pnpm-lock.yaml", "lockfileVersion: '9.0'\nimporters:\n  .:\n    dependencies:\n      vuln-pkg: {specifier: ^1.0.0, version: 1.0.0}\n", false},
		{"pnpm-lock.yaml", "packages: {}\n", false},
		{"pnpm-lock.yaml", "[not: yaml", false},
	} {
		err := checkContent(c.name, []byte(c.body))
		if (err == nil) != c.empty {
			t.Errorf("%s %q: err %v, want empty=%t", c.name, c.body, err, c.empty)
		}
	}
}

func TestRunScansYarnLockOffline(t *testing.T) {
	e := newEnv(t, "demo-yarn")
	r := e.run(t)
	if r.Status != ScanOK || len(r.Manifests) != 1 {
		t.Fatalf("status %s manifests %+v errors %v", r.Status, r.Manifests, r.Errors)
	}
	fs, _ := e.repo.ListFindings(context.Background(), e.proj.ID, "")
	if len(fs) != 1 || fs[0].ManifestRelPath != "yarn.lock" || fs[0].Package != "vuln-pkg" || fs[0].Kind != "dependency" {
		t.Errorf("findings = %+v", fs)
	}
}

