package analyze

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

// errFormat is the cause of a lockfile Michel cannot parse; AnalyzeWith
// reports it as the reason the dependency graph is unavailable.
const errFormat = "lockfile format not understood"

// loadYarn reads yarn.lock, classic (v1) or berry (v2+, YAML), and the root
// package.json.
func loadYarn(dir string) (*DepGraph, error) {
	raw, err := os.ReadFile(filepath.Join(dir, "yarn.lock"))
	if err != nil {
		return nil, fmt.Errorf("read yarn.lock: %w", err)
	}
	g := &DepGraph{Ecosystem: "npm", Root: map[string]string{}, Requires: map[string][]string{}}
	if isYarnV1(raw) {
		parseYarnV1(raw, g)
	} else if err := parseYarnBerry(raw, g); err != nil {
		return nil, err
	}
	if err := rootFromPackageJSON(dir, g); err != nil {
		return nil, err
	}
	return g, nil
}

// isYarnV1 tells a classic lockfile by its generated header.
func isYarnV1(raw []byte) bool {
	for _, l := range strings.Split(string(raw), "\n") {
		l = strings.TrimSpace(l)
		if l == "" {
			continue
		}
		return strings.HasPrefix(l, "# THIS IS AN AUTOGENERATED FILE") || strings.Contains(l, "yarn lockfile v1")
	}
	return false
}

// yarnNames returns the package names of a block header such as
// `"vuln-pkg@^1.0.0", vuln-pkg@~1.0.0:` or `"vuln-pkg@npm:^1.0.0, vuln-pkg@npm:~1.0.0":`.
func yarnNames(header string) []string {
	header = strings.TrimSuffix(strings.TrimSpace(header), ":")
	var out []string
	for _, spec := range strings.Split(header, ",") {
		spec = strings.Trim(strings.TrimSpace(spec), `"'`)
		if n := specName(spec); n != "" && !contains(out, n) {
			out = append(out, n)
		}
	}
	return out
}

// specName is the name in "name@range", keeping the @ of a scope.
func specName(spec string) string {
	i := strings.Index(strings.TrimPrefix(spec, "@"), "@")
	if i < 0 {
		return ""
	}
	if strings.HasPrefix(spec, "@") {
		i++
	}
	return spec[:i]
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// addRequires records deps as requirements of every name, merging the
// versions of one package (the graph is by name).
func addRequires(g *DepGraph, names, deps []string) {
	for _, n := range names {
		cur := g.Requires[n]
		if cur == nil {
			cur = []string{}
		}
		for _, d := range deps {
			if !contains(cur, d) {
				cur = append(cur, d)
			}
		}
		g.Requires[n] = cur
	}
}

// parseYarnV1 reads the blocks of a classic lockfile: an unindented header,
// then two-space properties, the dependency sections listing one
// four-space `name "range"` line per dependency.
func parseYarnV1(raw []byte, g *DepGraph) {
	sc := bufio.NewScanner(bytes.NewReader(raw))
	sc.Buffer(make([]byte, 0, 64*1024), 4<<20)
	var names, deps []string
	inDeps := false
	flush := func() {
		if len(names) > 0 {
			addRequires(g, names, deps)
		}
		names, deps, inDeps = nil, nil, false
	}
	for sc.Scan() {
		line := strings.TrimRight(sc.Text(), " \t\r")
		switch {
		case line == "" || strings.HasPrefix(strings.TrimSpace(line), "#"):
		case !strings.HasPrefix(line, " "):
			flush()
			if strings.HasSuffix(line, ":") {
				names = yarnNames(line)
			}
		case strings.HasPrefix(line, "    "):
			if inDeps {
				if f := strings.Fields(line); len(f) > 0 {
					deps = append(deps, strings.Trim(strings.TrimSuffix(f[0], ":"), `"'`))
				}
			}
		default: // a two-space property
			p := strings.TrimSpace(line)
			inDeps = p == "dependencies:" || p == "optionalDependencies:"
		}
	}
	flush()
}

// parseYarnBerry reads a berry lockfile: a YAML map from block header to
// {version, dependencies, optionalDependencies}, with __metadata.
func parseYarnBerry(raw []byte, g *DepGraph) error {
	var doc map[string]struct {
		Dependencies         map[string]any `yaml:"dependencies"`
		OptionalDependencies map[string]any `yaml:"optionalDependencies"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return fmt.Errorf("yarn.lock: %s: %w", errFormat, err)
	}
	if _, ok := doc["__metadata"]; !ok {
		return fmt.Errorf("yarn.lock: %s: neither the classic header nor __metadata", errFormat)
	}
	for header, e := range doc {
		// The project itself (name@workspace:.) is not a dependency.
		if header == "__metadata" || strings.Contains(header, "@workspace:") {
			continue
		}
		var deps []string
		for d := range e.Dependencies {
			deps = append(deps, d)
		}
		for d := range e.OptionalDependencies {
			deps = append(deps, d)
		}
		addRequires(g, yarnNames(header), deps)
	}
	return nil
}
